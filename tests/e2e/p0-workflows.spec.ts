type BoxMetric = 'width' | 'height' | 'x' | 'y'

const expectBox = async (page: Page, selector: string, expected: Partial<Record<BoxMetric, number>>, tolerance = 2): Promise<void> => {
  const box = await page.locator(selector).boundingBox()
  expect(box, `${selector} should be visible`).not.toBeNull()
  for (const [key, value] of Object.entries(expected) as Array<[BoxMetric, number]>) expect(Math.round(box![key])).toBeGreaterThanOrEqual(value - tolerance)
  for (const [key, value] of Object.entries(expected) as Array<[BoxMetric, number]>) expect(Math.round(box![key])).toBeLessThanOrEqual(value + tolerance)
}

