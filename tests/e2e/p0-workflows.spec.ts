const waitForScreenSettled = async (page: Page): Promise<void> => {
  await page.locator('.screen.active').evaluate(async (screen) => {
    const animations = screen.getAnimations().filter((animation) => animation.playState === 'running')
    await Promise.allSettled(animations.map((animation) => animation.finished))
    await new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve())))
  })
}
