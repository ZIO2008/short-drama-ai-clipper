import { expect, test } from '@playwright/test'
import { openModuleStaticHarness } from '../helpers/clip-module-static-harness.js'

test('real packaging controls keep preview and export configuration aligned', async ({}, info) => {
  const harness = await openModuleStaticHarness('clip-pool', 'runtime')
  try {
    const frame = harness.page.frameLocator('iframe')
    await expect(frame.locator('[data-clip-export-candidate="e1-c01"]')).toBeVisible()
    await frame.locator('[data-clip-export-candidate="e1-c01"]').check()
    await frame.locator('[data-clip-export-open]').first().click()
    await frame.locator('#configurePackagingFromExport').click()
    await expect(frame.locator('#packagingModal')).toHaveAttribute('aria-hidden', 'false')
    await expect(frame.locator('#packagePreset')).toBeFocused()
    await frame.locator('#savePackaging').focus()
    await harness.page.keyboard.press('Tab')
    await expect(frame.locator('#closePackaging')).toBeFocused()
    await harness.page.keyboard.press('Shift+Tab')
    await expect(frame.locator('#savePackaging')).toBeFocused()
    await frame.locator('[data-package-aspect="landscape"]').click()
    await expect(frame.locator('#packagePreview')).toHaveAttribute('data-aspect', 'landscape')
    await expect(frame.locator('#packageAspectLabel')).toContainText('横屏 16:9')
    await frame.locator('#packageTitleInput').fill('独立包装标题')
    await frame.locator('#packagePromptInput').fill('追更提示')
    await frame.locator('#packageBadge').selectOption({ label: '热门短剧' })
    await frame.locator('#packageTitleSize').selectOption('large')
    await frame.locator('#packageOverlay').selectOption('strong')
    await expect(frame.locator('#packagePreviewTitle')).toHaveText('独立包装标题')
    await expect(frame.locator('#packagePreviewPrompt')).toHaveText('追更提示')
    await expect(frame.locator('#packagePreviewBadge')).toHaveText('热门短剧')
    expect(await frame.locator('#packagePreview').evaluate(node => node.style.getPropertyValue('--package-title-size'))).toBe('38px')
    expect(await frame.locator('#packagePreview').evaluate(node => node.style.getPropertyValue('--package-overlay'))).toBe('44%')
    await harness.page.screenshot({ path: info.outputPath('packaging-landscape-live.png') })
    await harness.page.keyboard.press('Escape')
    await expect(frame.locator('#packagingModal')).toHaveAttribute('aria-hidden', 'true')
    await expect(frame.locator('#exportModal')).toHaveAttribute('aria-hidden', 'false')
    await expect(frame.locator('#configurePackagingFromExport')).toBeFocused()
    await frame.locator('#configurePackagingFromExport').click()
    await expect(frame.locator('#packagePreviewTitle')).toHaveText('独立包装标题')
    await frame.locator('[data-package-aspect="portrait"]').click()
    await expect(frame.locator('#packagePreview')).toHaveAttribute('data-aspect', 'portrait')
    await frame.locator('#savePackaging').click()
    await expect(frame.locator('#exportModal .package-summary')).toContainText('竖屏 9:16')
    if (!await frame.locator('#exportPackageToggle').evaluate(node => node.classList.contains('on'))) await frame.locator('#exportPackageToggle').click()
    await frame.locator('#saveExport').click()
    const config = await harness.page.evaluate(() => (window as unknown as { fixtureProbe: { preflightConfig: { outputSize: string; packagingEnabled: boolean; packaging: { aspect: string; title: string; prompt: string; titleSize: string; overlay: string } } } }).fixtureProbe.preflightConfig)
    expect(config).toMatchObject({ outputSize: '1080x1920', packagingEnabled: true, packaging: { aspect: 'portrait', title: '独立包装标题', prompt: '追更提示', titleSize: 'large', overlay: 'strong' } })
  } finally { await harness.close() }
})
